import argparse
import json

import pandas as pd

from .scoring import (
    score_buyer_product,
)


# ============================================================
# PREDICT
# ============================================================

def predict(
    data,
):

    required = [

        "buyer_id",
        "buyer_region",
        "preferred_category",
        "preferred_material",
        "min_budget",
        "max_budget",
        "previous_category",
        "previous_material",
        "product_category",
        "product_material",
        "product_price",
        "product_region",
        "product_demand_score",
    ]

    missing = [
        field

        for field in required

        if field not in data
    ]

    if missing:

        raise ValueError(
            "Missing required fields:\n"
            + "\n".join(
                f"  - {field}"
                for field in missing
            )
        )

    row = pd.Series(
        data
    )

    result = score_buyer_product(
        row
    )

    result[
        "engine"
    ] = (
        "Hybrid Buyer Matching Engine"
    )

    result[
        "engine_version"
    ] = "1.0.0"

    result[
        "data_type"
    ] = (
        "synthetic_pipeline_testing_data"
    )

    result[
        "research_valid"
    ] = False

    result[
        "warning"
    ] = (
        "This recommendation is "
        "generated by a prototype "
        "rule-based hybrid engine using "
        "synthetic pipeline-testing data."
    )

    return result


