import argparse
import json

import pandas as pd

from .scoring import score_market


# ============================================================
# PREDICT
# ============================================================

def predict_market_opportunity(
    market_data,
):

    required_fields = [
        "product_category",
        "region",
        "demand_score",
        "price_opportunity",
        "market_growth",
        "regional_fit",
        "seasonality_score",
        "competition_score",
    ]

    missing_fields = [
        field

        for field in required_fields

        if field not in market_data
    ]

    if missing_fields:

        raise ValueError(
            "Missing required fields:\n"
            + "\n".join(
                f"  - {field}"
                for field in missing_fields
            )
        )

    row = pd.Series(
        {
            key:
                value

            for key, value
            in market_data.items()
        }
    )

    result = score_market(
        row
    )

    result[
        "engine"
    ] = (
        "Explainable Market "
        "Opportunity Engine"
    )

    result[
        "engine_version"
    ] = "1.0.0"

    result[
        "data_type"
    ] = (
        "synthetic_pipeline_testing_data"
    )

    result[
        "research_valid"
    ] = False

    result[
        "warning"
    ] = (
        "This opportunity score is "
        "generated by a prototype "
        "rule-based engine using "
        "synthetic pipeline-testing data."
    )

    return result


# ============================================================
# CLI
# ============================================================

def main():

    parser = argparse.ArgumentParser(
        description=(
            "KalaSetu Market Opportunity AI"
        )
    )

    parser.add_argument(
        "--product-category",
        required=True,
    )

    parser.add_argument(
        "--region",
        required=True,
    )

    parser.add_argument(
        "--demand",
        required=True,
        type=float,
    )

    parser.add_argument(
        "--price-opportunity",
        required=True,
        type=float,
    )

    parser.add_argument(
        "--market-growth",
        required=True,
        type=float,
    )

    parser.add_argument(
        "--regional-fit",
        required=True,
        type=float,
    )

    parser.add_argument(
        "--seasonality",
        required=True,
        type=float,
    )

    parser.add_argument(
        "--competition",
        required=True,
        type=float,
    )

    args = parser.parse_args()

    market_data = {

        "product_category":
            args.product_category,

        "region":
            args.region,

        "demand_score":
            args.demand,

        "price_opportunity":
            args.price_opportunity,

        "market_growth":
            args.market_growth,

        "regional_fit":
            args.regional_fit,

        "seasonality_score":
            args.seasonality,

        "competition_score":
            args.competition,
    }

    print("=" * 70)

    print(
        "KALASETU - MARKET OPPORTUNITY AI"
    )

    print("=" * 70)

    print(
        "\nMarket Input:"
    )

    for key, value in (
        market_data.items()
    ):

        print(
            f"  {key:<22}: {value}"
        )

    print(
        "\nCalculating opportunity..."
    )

    result = predict_market_opportunity(
        market_data
    )

    print(
        "\n" + "=" * 70
    )

    print(
        "MARKET OPPORTUNITY RESULT"
    )

    print(
        "=" * 70
    )

    print(
        f"\nOpportunity Score : "
        f"{result['opportunity_score']:.2f}"
    )

    print(
        f"Opportunity Level : "
        f"{result['opportunity_level']}"
    )

    print(
        f"\nExplanation:\n"
        f"{result['explanation']}"
    )

    print(
        "\nFactor Contributions:"
    )

    for key, value in (
        result[
            "factor_contributions"
        ].items()
    ):

        print(
            f"  {key:<22}: "
            f"{value:.2f}"
        )

    print(
        "\nResearch Valid:"
        f" {result['research_valid']}"
    )

    print(
        "\nJSON Result:"
    )

    print(
        json.dumps(
            result,
            indent=4,
        )
    )

    print(
        "\n" + "=" * 70
    )

    print(
        "PREDICTION TEST PASSED"
    )

    print(
        "=" * 70
    )


if __name__ == "__main__":
    main()